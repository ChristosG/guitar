@pytest.mark.parametrize("prompt_id", COURSE_LANGUAGE_PROMPTS)
def test_the_curriculum_preview_does_not_follow_the_cockpit_locale(prompt_id):
    """Chris spotted this from the screen, and it was real:

        PREVIEW   (X-App-Locale: el):  "write everything you produce in Greek (el)"
        REAL CALL (a course whose language is 'en'): "...in English (en)"

    The registry rendered these with `language=locale` — the SETTINGS PAGE's locale.
    The live path passes the COURSE's language, which comes from the STUDENT
    (`interview.py:311`). So flipping the cockpit to English used to flip this preview
    to English while a Greek student's course stayed Greek: a screen presenting a value
    it does not own as one it does.

    In his live DB, 5 of 6 courses are `en` and 131 of 155 lessons are English. The
    engine is right. This is the viewer being made to stop arguing with it.
    """
    from app.prompts import registry

    el = registry.render(prompt_id, "el").text
    en = registry.render(prompt_id, "en").text
    assert el == en, (
        f"{prompt_id} still changes with the cockpit locale. Its language belongs to "
        f"the course, and no control on the Settings page moves it."
    )


@pytest.mark.parametrize("prompt_id", COURSE_LANGUAGE_PROMPTS)
def test_the_language_span_says_where_the_language_actually_comes_from(prompt_id):
    """The ORIGIN is the surprising part, and it is exactly what he asked about — so
    it is on the chip, not in a footnote."""
    from app.prompts import registry

    spans = registry.render(prompt_id, "el").spans
    lang = [s for s in spans if s.name in ("language_directive", "answer_in")]
    assert lang, f"{prompt_id} interpolates a language directive but marks no span"
    assert any("μαθητή" in s.label_el for s in lang), (
        f"{prompt_id}: the language span must name its origin — the student's/course's "
        f"language — because that is the fact he could not have guessed from the screen."
    )


def test_he_can_preview_a_course_prompt_in_either_language():
    """The honest third option: he does not have to take our word for the origin — he
    can look at both. `?course_language=` is what the card's toggle calls."""
    from app.prompts import registry

    greek = registry.render("curriculum.outline", "el", None, "el").text
    english = registry.render("curriculum.outline", "el", None, "en").text
    assert "in Greek (el)" in greek
    assert "in English (en)" in english


@pytest.mark.parametrize("prompt_id_ui", ["chat.system", "retrieval.grounded", "artifacts.generate", "lesson.from_selection"])
def test_the_cockpit_locale_still_drives_the_prompts_it_actually_drives(prompt_id_ui):
    """The other half, and the reason this is not a blanket change: chat, retrieval,
    artifacts and lesson-from-selection DO take the cockpit locale on the live path
    (`lessons/draft.py`'s own docstring: "the tutor's UI locale, threaded all the way
    from the browser's X-App-Locale"). Freezing those would be the same bug, mirrored."""
    from app.prompts import registry

    el = registry.render(prompt_id_ui, "el").text
    en = registry.render(prompt_id_ui, "en").text
    assert el != en, (
        f"{prompt_id_ui} takes the cockpit locale on the live path, so the preview "
        f"must follow it."
    )
